const CHAR_MAP = new Map()
for (let i = 0; i < HANS.length; i++) CHAR_MAP.set(HANS[i], HANT[i])

export function toTraditional(text) {
  if (typeof text !== 'string' || !text) return text
  let out = text
  for (const [src, dst] of PHRASES) {
    if (out.includes(src)) out = out.replaceAll(src, dst)
  }
  let res = ''
  for (const ch of out) res += CHAR_MAP.get(ch) ?? ch
  return res
}

export function convertDict(dict) {
  const out = {}
  for (const [k, v] of Object.entries(dict)) out[k] = toTraditional(v)
  return out
}

export function convertHostErrors(pairs) {
  return pairs.map(([re, replacement]) => [re, toTraditional(replacement)])
}
